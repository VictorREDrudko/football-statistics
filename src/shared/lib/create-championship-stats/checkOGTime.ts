export const checkOGTime = (timeGoals: string) => {
  // Удаляем все вхождения "94(o.g.)" вместе с возможными запятыми вокруг
  let cleaned = timeGoals.replace(/(,\s*)?94\(o\.g\.\)(,\s*)?/g, (match, p1, p2) => {
    // Если есть запятая и перед, и после → заменяем на одну запятую
    if (p1 && p2) return ',';
    // В остальных случаях просто удаляем (включая возможные запятые)
    return '';
  });

  // Удаляем возможные двойные запятые ", ," → ","
  cleaned = cleaned.replace(/,\s*,/g, ',');

  // Удаляем запятую в начале строки (если есть)
  cleaned = cleaned.replace(/^,\s*/, '');

  // Удаляем запятую в конце строки (если есть)
  cleaned = cleaned.replace(/,\s*$/, '');

  // Если строка пустая после удаления (было только "94(o.g.)"), возвращаем ''
  return cleaned.trim() === '' ? '' : cleaned.trim();
}